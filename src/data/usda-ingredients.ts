export function computeGramWeight(
  ingredientId: string,
  quantity: number,
  unit: string
): number {
  const ref = USDA_INGREDIENTS[ingredientId];
  if (!ref) return quantity * 50;
  const normalizedUnit = unit.toLowerCase().replace(/s$/, "");
  const genericFallbacks: Record<string, number> = {
    g: 1,
    ml: 1,
    kg: 1000,
    l: 1000,
    oz: 28.35,
    lb: 453.6,
    tbsp: 15,
    tsp: 5,
    pinch: 0.3,
    dash: 0.5,
    sprig: 2,
    leaf: 1,
    handful: 30,
  };
  const factor =
    ref.unitGrams[normalizedUnit] ??
    ref.unitGrams[unit.toLowerCase()] ??
    genericFallbacks[normalizedUnit] ??
    ref.unitGrams.piece ??
    ref.unitGrams.cup ??
    100;
  return Math.round(quantity * factor * 10) / 10;
}

